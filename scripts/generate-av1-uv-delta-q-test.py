"""Generate the separate_uv_delta_q white-box test.

The fixtures are two reduced-still 64x64 8-bit 4:2:0 streams that only differ
in quantization_params:

* ``uvdq_src.obu``      aomenc with --deltaq-mode=3 --enable-chroma-deltaq=1,
                        which emits non-zero U deltas (u_dc = u_ac = 2) while
                        leaving V to reuse them. Streams like this were
                        rejected before per-plane deltas were supported.
* ``uvdq_separate.obu`` the same stream rewritten by
                        ``_refs/make_uvdq_stream.py`` to signal
                        separate_uv_delta_q with diff_uv_delta = 1 and an
                        independent V pair (v_dc = 5, v_ac = -3). dav1d and
                        FFmpeg both decode it, and the rewrite with V = U
                        reproduces the source byte for byte, so the only
                        difference in the truth files is the V plane.

Every expectation is dav1d 1.2.1 output.
"""

import sys

DIR = "tests/fixtures/av1-uv-delta-q"
OUT = "av1_uv_delta_q_wbtest.mbt"


def moon_bytes(data, per_line=12):
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        lines.append(
            "    " + ", ".join("b'\\x%02X'" % b for b in chunk) + ","
        )
    return "\n".join(lines)


def digest(samples):
    h = 0
    for i, s in enumerate(samples):
        v = s & 0xFF
        h ^= (v + (i & 0xFF))
        h = ((h << 5) & 0xFFFFFF) | ((h >> 19) & 0x1F)
        h &= 0xFFFFFF
    return h


def truth(name):
    d = open("%s/%s" % (DIR, name), "rb").read()[:6144]
    y, u, v = d[:4096], d[4096:5120], d[5120:]
    return (digest(y), digest(u), digest(v), list(y[:4]), list(u[:4]),
            list(v[:4]))


