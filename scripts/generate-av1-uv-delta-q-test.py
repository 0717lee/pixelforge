def main():
    sep = open("%s/uvdq_separate.obu" % DIR, "rb").read()
    shared = open("%s/uvdq_src.obu" % DIR, "rb").read()
    body = (
        HEADER
        + moon_bytes(sep)
        + "\n"
        + MIDDLE
        + moon_bytes(shared)
        + "\n"
        + FOOTER
    )
    open(OUT, "w", newline="\n").write(body)
    print("wrote", OUT)
    for name in ("uvdq_src_truth.yuv", "uvdq_separate_truth.yuv"):
        t = truth(name)
        print("  %-22s Y=%d U=%d V=%d" % (name, t[0], t[1], t[2]))


if __name__ == "__main__":
    sys.exit(main())
