#!/usr/bin/env python3
"""Generate the AV1 subpel interpolation filter table from the cached go-av1 source.

    python scripts/generate-av1-interp-tables.py
    python scripts/generate-av1-interp-tables.py --check

`subpelFilters[filter_type][fractional_pel][8]` is the normative Subpel_Filters
table (AV1 §7.11.3.4). The source hash is pinned so a changed cache cannot
silently alter motion compensation. These are plain coefficient rows, not CDFs,
so nothing here needs to be freshly allocated per tile.
"""

